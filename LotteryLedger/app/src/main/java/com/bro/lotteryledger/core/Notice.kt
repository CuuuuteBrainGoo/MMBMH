package com.bro.lotteryledger.core

/**
 * 提示条的配色类型（少爷 2026-09-27 指定）。
 *
 * 起因：以前提示只有一段文字，**「中了 15 块」「没中奖」「过期作废」长得一模一样**，
 * 用户得一格格读字才知道是好消息还是坏消息。现在由界面按类型上色，扫一眼就分得清。
 *
 * | 类型 | 颜色 | 用在 |
 * |---|---|---|
 * | [WIN] | 红（中国红） | 中奖 |
 * | [LOSE] | 绿 | 未中奖 |
 * | [WARN] | 黄 | 彩票过期 / 需要你手动处理 |
 * | [ERROR] | 暗橙 | 操作失败（**刻意跟中奖的红错开**，否则「核验失败」会被当成好消息） |
 * | [NEUTRAL] | 深灰 | 其它提示（保存成功、正在核验…… 不需要情绪的那些） |
 */
enum class NoticeKind {
    NEUTRAL,
    WIN,
    LOSE,
    WARN,
    ERROR
}

/**
 * 一条要弹给用户的提示：**文字 + 类型**。
 *
 * 两个字段是绑在一起的，就是不想再出现「文字换了颜色没换」那种错位 ——
 * 所以不做成两个平行的字段，而是一个不可分的数据类。
 */
data class Notice(
    val text: String,
    val kind: NoticeKind = NoticeKind.NEUTRAL
)
