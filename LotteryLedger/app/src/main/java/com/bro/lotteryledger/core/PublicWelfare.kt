package com.bro.lotteryledger.core

/**
 * 公益贡献金推算（少爷 2026-09-27 要求：首页台账加「公益贡献」合计）。
 *
 * ## 数据来源
 *
 * 财政部《2026 年第 24 号公告》明确：**福彩双色球、体彩超级大乐透的
 * 彩票公益金提取比例都是 36%**（奖金 51% + 发行费 13% + 公益金 36% = 100%）。
 *
 * 印证：一张 2 元的双色球/大乐透贡献 0.72 元公益金 —— 0.72 / 2 = 36% ✓
 * 大乐透 3 元追加票贡献 1.08 元 —— 1.08 / 3 = 36% ✓（追加部分同样按 36% 提取）
 *
 * 所以**票面金额 × 36%** 就是公益金，双色球和大乐透同一个比例，
 * 不需要按彩种区分。这也解释了票面上印的那句
 * 「感谢您为公益事业贡献 X 元」。
 *
 * ## 为什么是「推算」而不是读票面
 *
 * 票面确实印着这个数字，AI 也能读出来。但要把它存下来就得给数据库加字段，
 * 而当前 Room 配的是 `fallbackToDestructiveMigration()` ——
 * **加字段会清空少爷已经录好的真实账目**，这个代价换一个"更精确的小数"不值。
 *
 * 推算的误差只可能来自「票面金额本身读错了」，而那种情况
 * [TicketCrossCheck] 和本地的金额校验都会先报出来。
 */
object PublicWelfare {

    /**
     * 公益金提取比例：36%。
     *
     * 双色球和大乐透相同（财政部公告），所以不按彩种分支 ——
     * 少一个分支就少一处可能写错的地方。
     * 将来如果加别的彩种（比如七乐彩 37%、3D 34%），在这里按彩种分支。
     */
    const val RATIO = 0.36

    /** 由票面金额算公益贡献。金额为空或非正数时返回 0。 */
    fun fromAmount(amountYuan: Double?): Double {
        val a = amountYuan ?: return 0.0
        if (a <= 0.0) return 0.0
        return a * RATIO
    }

    /** 一批票的公益贡献合计。 */
    fun totalOf(amounts: Iterable<Double?>): Double =
        amounts.sumOf { fromAmount(it) }

    /**
     * 一句话说明，给界面显示用。
     *
     * 刻意写明「按 36% 估算」——不写的话，用户拿计算器一算发现和票面印的
     * 差几分钱（四舍五入），会以为程序算错了。
     */
    fun describe(totalYuan: Double): String =
        "按票面金额的 ${(RATIO * 100).toInt()}% 估算（双色球与大乐透的公益金提取比例）"
}
